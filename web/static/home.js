// Home page: hero, real counts from /info, cards to the pages and one seeded sample from the repo's generator.
import { route, api, app, esc } from './core.js';
import { FORM_NAMES } from './ui.js';

route('home', async () => {
  const [info, samples] = await Promise.all([api('/info'), api('/samples')]);
  const pick = samples.seeded[0];
  app().innerHTML = `
  <section class="hero">
    <p class="kicker">computational poetry · CMU pronouncing dictionary</p>
    <h1 class="glow">Poetry System</h1>
    <p class="lead">Generate haiku, tanka, sonnets and free verse from mood-categorised vocabularies, and analyse any poem's
      syllables, rhyme scheme and metre. The generator and prosody code are the repo's Python; on this site they run as a
      JavaScript port that gives the same poem for the same seed.</p>
    <a class="btn" href="#/compose">Compose a poem</a><a class="btn alt" href="#/analyse">Analyse a poem</a>
  </section>
  <div class="tiles">
    <div class="tile"><b>${Object.keys(info.forms).length}</b><span>forms: ${Object.keys(info.forms).map(f => FORM_NAMES[f]).join(', ')}</span></div>
    <div class="tile"><b>${info.moods.length}</b><span>moods: ${esc(info.moods.join(', '))}</span></div>
    <div class="tile"><b>${info.vocabulary_unique}</b><span>vocabulary words</span></div>
    <div class="tile"><b>${info.cmu_entries.toLocaleString('en')}</b><span>CMU dictionary pronunciations</span></div>
  </div>
  <div class="two">
    <div class="grid">
      <a class="card" href="#/compose"><b>Compose</b><small>haiku · tanka · sonnet · free verse</small>
        <span>Pick a form, a mood and a seed; every line shows its syllables and stress pattern.</span></a>
      <a class="card" href="#/analyse"><b>Analyse</b><small>syllables · rhyme · metre</small>
        <span>Paste a poem to see syllables per line, the rhyme scheme and CMU stress patterns.</span></a>
      <a class="card" href="#/gallery"><b>Gallery</b><small>samples from the repo</small>
        <span>The README's example output, the poems quoted in the code and seeded samples.</span></a>
      <a class="card" href="#/about"><b>About</b><small>how it works · run it</small>
        <span>The generation process, what runs where, and how to run the desktop demo and web app.</span></a>
    </div>
    <div class="panel">
      <h3>${FORM_NAMES[pick.form]} · mood ${esc(pick.mood || 'default')} · seed ${pick.seed}</h3>
      <pre class="poem" style="border:0;background:none;padding:0">${esc(pick.text)}</pre>
      <p class="small mute">Generated by the repo's Python at build time: <code>${esc(pick.call)}</code>.
        <a href="#/compose?form=${pick.form}&mood=${pick.mood || ''}&seed=${pick.seed}">Recreate it in Compose</a>.</p>
    </div>
  </div>`;
});
